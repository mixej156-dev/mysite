#!/usr/bin/env bash
# Export the committed code into a separate repository with a single commit: no working notes (CLAUDE.md, AGENTS.md,
# docs/, references/), no history. Run again after new work to add one more commit to the export.
#
#   scripts/export-clean.sh [target-dir]        (default: ../my-site-clean)
set -euo pipefail

SRC="$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"
DEST="${1:-$SRC/../my-site-clean}"
EXCLUDE=(CLAUDE.md AGENTS.md docs references scripts/export-clean.sh)

if [ -n "$(git -C "$SRC" status --porcelain)" ]; then
  echo "Commit or stash your changes first: only committed code is exported." >&2
  exit 1
fi

mkdir -p "$DEST"
if [ ! -d "$DEST/.git" ]; then
  git -C "$DEST" init -q -b main
fi

# Replace everything except .git with the current commit, minus the excluded paths
find "$DEST" -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
git -C "$SRC" archive HEAD | tar -x -C "$DEST"
for path in "${EXCLUDE[@]}"; do rm -rf "${DEST:?}/$path"; done
rmdir "$DEST/scripts" 2>/dev/null || true

# next dev writes AGENTS.md into any project; keep it out of the export
printf '\n# generated by next dev\nAGENTS.md\n' >> "$DEST/.gitignore"

git -C "$DEST" add -A
if git -C "$DEST" rev-parse -q --verify HEAD >/dev/null; then
  git -C "$DEST" diff --cached --quiet && { echo "Nothing new to export."; exit 0; }
  git -C "$DEST" commit -q -m "Update"
else
  git -C "$DEST" commit -q -m "Initial commit"
fi
echo "Exported to $DEST ($(git -C "$DEST" rev-list --count HEAD) commit(s))"
